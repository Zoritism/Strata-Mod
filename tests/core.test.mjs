const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '.work', 'tests'); fs.mkdirSync(root, { recursive: true });
function fixture(t) {
  const dir = fs.mkdtempSync(path.join(root, 'case-'));
  t.after(() => { if (!inside(root, dir) || dir === root) throw new Error('cleanup boundary'); fs.rmSync(dir, { recursive: true, force: true }); });
  const file = path.join(dir, 'storage.json'), config = defaultConfig('./data'); config.strict = false;
  atomicJSON(file, config); const p = validate(config, dir, { probe: true });
  return { dir, file, config, p };
}
test('persistent paths, relative roots, scoped environment, strict C and overlapping paths', t => {
  const { dir, file, config, p } = fixture(t);
  assert.deepEqual(readJSON(file), config);
  const before = process.env.TEMP, env = environment(p);
  assert.equal(env.TEMP, p.temp); assert.equal(process.env.TEMP, before);
  assert.equal(env.WEBVIEW2_USER_DATA_FOLDER, p.webview);
  assert.throws(() => validate({ ...config, paths: { temp: './home/nested' } }, dir), /перекрываются/);
  if (process.platform === 'win32') assert.throws(() => validate({ ...config, strict: true, paths: { temp: 'C:\\strata-test' } }, dir), /C:/);
  assert.throws(() => validate({ ...config, paths: { misspelled: 'foo' } }, dir), /категория/);
});
test('pending copy applies only before launch; binary and JSON bytes verified, source kept', async t => {
  const { dir, file, config, p } = fixture(t);
  fs.writeFileSync(path.join(p.home, 'history.json'), JSON.stringify({ chats: [{ id: 'a', messages: ['Привет', 'Чайник'], extra: { edited: true } }] }));
  fs.writeFileSync(path.join(p.home, 'data.bin'), Buffer.from([0, 255, 1, 4]));
  const next = { ...config, paths: { home: '../new-home', temp: '../new-temp' } };
  stage(file, next, 1, 'copy'); assert.equal(readJSON(file).revision, 1);
  assert.throws(() => stage(file, next, 1, 'copy'), /ожидающее/);
  await applyPending(file); assert.equal(readJSON(file).revision, 2);
  const moved = effective(readJSON(file), dir);
  assert.deepEqual(fs.readFileSync(path.join(p.home, 'history.json')), fs.readFileSync(path.join(moved.home, 'history.json')));
  assert.deepEqual(fs.readFileSync(path.join(p.home, 'data.bin')), fs.readFileSync(path.join(moved.home, 'data.bin')));
  assert.equal(readJSON(file + '.previous').revision, 1);
  assert.equal(await applyPending(file), null);
  assert.throws(() => stage(file, config, 1, 'existing'), /изменились/);
});
test('failed copying never switches settings; partial verified copy resumes', async t => {
  const { dir, file, config, p } = fixture(t);
  fs.writeFileSync(path.join(p.home, 'one'), 'unique');
  stage(file, { ...config, paths: { home: '../new-home' } }, 1, 'copy');
  const dest = path.join(dir, 'new-home'); fs.mkdirSync(dest); fs.writeFileSync(path.join(dest, 'one'), 'other');
  await assert.rejects(applyPending(file), /отличается/); assert.equal(readJSON(file).revision, 1);
  fs.writeFileSync(path.join(dest, 'one'), 'unique');
  await applyPending(file); assert.equal(readJSON(file).revision, 2);
});
